"""Unit tests for the PDF certificate generator.

No database, no HTTP, no Celery — pure function tests.
"""
from __future__ import annotations

from datetime import date

import pytest

from app.certificate.generator import (
    CertificateData,
    CertificateGenerationError,
    _fit_recipient_name,
    generate_certificate_pdf,
)


def _make_data(**kwargs) -> CertificateData:
    defaults = dict(
        recipient_name="Alice Johnson",
        certificate_title="Certificate of Completion",
        event_name="Python Bootcamp 2026",
        issuer_name="Example Organization",
        issue_date=date(2026, 10, 7),
    )
    defaults.update(kwargs)
    return CertificateData(**defaults)


class TestGenerateCertificatePdf:
    def test_returns_bytes(self):
        data = _make_data()
        result = generate_certificate_pdf(data)
        assert isinstance(result, bytes)
        assert len(result) > 100

    def test_valid_pdf_header(self):
        """Generated bytes must start with the PDF magic number."""
        data = _make_data()
        result = generate_certificate_pdf(data)
        assert result[:4] == b"%PDF"

    def test_unicode_name(self):
        """Names with accented or CJK characters must not raise."""
        data = _make_data(recipient_name="Héloïse Dumont-Ångström")
        result = generate_certificate_pdf(data)
        assert result[:4] == b"%PDF"

    def test_long_name_does_not_crash(self):
        """A 120-character name must be handled gracefully."""
        long_name = "A" * 120
        data = _make_data(recipient_name=long_name)
        result = generate_certificate_pdf(data)
        assert result[:4] == b"%PDF"

    def test_minimal_name(self):
        data = _make_data(recipient_name="X")
        result = generate_certificate_pdf(data)
        assert result[:4] == b"%PDF"

    def test_pdf_size_reasonable(self):
        """PDF must be larger than 1 KB (has real content)."""
        data = _make_data()
        result = generate_certificate_pdf(data)
        assert len(result) > 1024


class TestFitRecipientName:
    def test_short_name_unchanged(self):
        name, size = _fit_recipient_name("Alice")
        assert name == "Alice"
        assert size == pytest.approx(36, abs=1)

    def test_very_long_name_reduced_font(self):
        long_name = "A" * 60
        name, size = _fit_recipient_name(long_name)
        # Should reduce font or wrap
        assert size <= 36

    def test_wrappable_name(self):
        name = "Christopher Alexander Bartholomew"
        _, size = _fit_recipient_name(name)
        # Should still fit (wraps at ~30 chars)
        assert size >= 18
